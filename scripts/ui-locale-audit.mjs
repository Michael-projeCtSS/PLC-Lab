export function auditUi(directory = path.join(root, "packages/ui/src")) {
  const results = [];
  function scan(dir) {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const file = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        if (entry.name !== "locale") scan(file);
        continue;
      }
      if (!file.endsWith(".tsx") || file.includes(".test.")) continue;
      const source = ts.createSourceFile(
        file,
        readFileSync(file, "utf8"),
        ts.ScriptTarget.Latest,
        true,
        ts.ScriptKind.TSX,
      );
      function visit(node) {
        const literal =
          ts.isJsxText(node) ||
          (ts.isStringLiteral(node) &&
            ((ts.isJsxAttribute(node.parent) &&
              ["title", "aria-label", "placeholder"].includes(
                node.parent.name.getText(source),
              )) ||
              (ts.isPropertyAssignment(node.parent) &&
                ["label", "title", "description"].includes(
                  node.parent.name.getText(source),
                ))));
        const text = literal ? node.text.trim().replace(/\s+/g, " ") : "";
        if (
          text &&
          /[a-z]{3}/i.test(text) &&
          !/^[a-z]+\.[a-zA-Z.]+$/.test(text) &&
          !technical.has(text) &&
          !text.includes("data-testid")
        )
          results.push({
            file: path.relative(root, file).replaceAll(path.sep, "/"),
            line:
              source.getLineAndCharacterOfPosition(node.getStart(source)).line +
              1,
            text,
          });
        ts.forEachChild(node, visit);
      }
      visit(source);
    }
  }
  scan(directory);
  return results;
}
if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const rows = auditUi();
  const report =
    "# Polish UI literal audit\n\nGenerated by `node scripts/ui-locale-audit.mjs --write`. These are review candidates, not an inferred coverage percentage. JSX prose and literal accessibility/form labels are inspected; protocol names and common engineering tokens are allowlisted. Backend/device data, runtime messages, source metadata and dynamic expressions require manual review. Tests and dictionaries are excluded.\n\n" +
    `${rows.length} literal candidates remain, mainly in Advanced engineering tools. These are tracked localization gaps, not all approved English exceptions.\n\n` +
    rows
      .map(
        (row) =>
          `- ${row.file}:${row.line} — ${row.text.replaceAll("\n", " ")}`,
      )
      .join("\n") +
    "\n";
  if (process.argv.includes("--write"))
    writeFileSync(
      path.join(root, "docs/validation/POLISH_UI_AUDIT.md"),
      report,
    );
  else console.log(report);
}
